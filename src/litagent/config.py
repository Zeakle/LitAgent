class RelevanceConfig(BaseModel):
    """Configure relevance settings."""

    max_papers: int = Field(default=50, gt=0, le=200)
    min_papers: int = Field(default=10, ge=0, le=200)
    cross_encoder_min_score: float | None = None
    lexical_min_score: float = Field(default=0.0, ge=0.0, le=3.0)

    @model_validator(mode="after")
    def _validate_policy(self):
        if self.min_papers > self.max_papers:
            raise ValueError("relevance.min_papers must be <= max_papers")
        if self.cross_encoder_min_score is not None and not math.isfinite(
            self.cross_encoder_min_score
        ):
            raise ValueError("cross_encoder_min_score must be finite or null")
        return self


class ChunkStrategy(str, Enum):
    """Select the deterministic chunk policy used for PDF clean blocks."""

    PAGE_BLOCK = "page_block"
    RECURSIVE = "recursive"
    SECTION_AWARE = "section_aware"



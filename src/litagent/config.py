class AppConfig(BaseModel):
    """Aggregate all LitAgent configuration sections."""

    agent: AgentConfig
    logging: LoggingConfig
    memory: MemoryConfig = MemoryConfig()
    context: ContextConfig = ContextConfig()
    orchestrator: OrchestratorConfig = OrchestratorConfig()
    llm: LLMConfig = LLMConfig()
    adversarial: AdversarialConfig = AdversarialConfig()
    mcp_servers: dict[str, MCPServerConfig] = {}
    safety: SafetyConfig = SafetyConfig()
    resilience: ResilienceConfig = ResilienceConfig()
    extractor: ExtractorConfig = ExtractorConfig()
    relevance: RelevanceConfig = RelevanceConfig()
    rag: RAGConfig = RAGConfig()
    observability: ObservabilityConfig = ObservabilityConfig()
    eval: EvalConfig = EvalConfig()
    planner: PlannerConfig = PlannerConfig()

    @model_validator(mode="after")
    def _validate_cross_component_limits(self):
        if self.relevance.max_papers > self.extractor.max_papers:
            raise ValueError("relevance.max_papers must be <= extractor.max_papers")
        return self


def _find_project_root() -> Path:
    current = Path(__file__).resolve().parent
    for parent in current.parents:
        if (parent / "pyproject.toml").exists():
            return parent
    raise FileNotFoundError("Cannot find project root (no pyproject.toml found)")


def _find_config_file(config_path: str | None = None) -> Path:
    """Resolve the explicit, environment, or default configuration path."""
    if config_path:
        path = Path(config_path)
    elif os.environ.get("LITAGENT_CONFIG"):
        path = Path(os.environ["LITAGENT_CONFIG"])
    else:
        path = _find_project_root() / "config" / "default.yaml"

    if not path.exists():
        raise FileNotFoundError(f"Config file not found: {path}")
    return path


def _apply_env_overrides(data: dict, prefix: str = "LITAGENT_") -> dict:
    """Apply declared environment overrides while preserving value types."""
    for env_key, env_val in os.environ.items():
        if not env_key.startswith(prefix):
            continue

        rest = env_key[len(prefix) :].lower()

        parts = rest.split("_", 1)
        if len(parts) != 2:
            continue

        section, key = parts

        # Ignore unknown names so typos cannot create undeclared settings.
        if section in data and isinstance(data[section], dict) and key in data[section]:
            original = data[section][key]

            # bool must be checked before int because bool subclasses int.
            if isinstance(original, bool):
                data[section][key] = env_val.strip().lower() in (
                    "1",
                    "true",
                    "yes",
                    "on",
                )
            elif isinstance(original, int):
                data[section][key] = int(env_val)
            elif isinstance(original, float):
                data[section][key] = float(env_val)
            else:
                data[section][key] = env_val

    return data


def load_config(config_path: str | None = None) -> AppConfig:
    """Load, override, and validate the application configuration."""

    config_file = _find_config_file(config_path)

    with open(config_file, "r", encoding="utf-8") as f:
        raw = yaml.safe_load(f)

    raw = _apply_env_overrides(raw)

    try:
        return AppConfig(**raw)
    except ValidationError as e:
        from litagent.exceptions import ConfigError

        raise ConfigError(f"Invalid config: {e}") from e
